// Invoked by the synthetic real-HTTP fixture with PIT_SOURCE_BROWSER=1.
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
export async function verifySourceRegistryBrowser({ origin, cookie, postId }) {
  const require=createRequire(import.meta.url);
  const {chromium}=require(process.env.PIT_PLAYWRIGHT_MODULE || "playwright");
  const directory=resolve("artifacts/source-registry");mkdirSync(directory,{recursive:true});
  const browser=await chromium.launch({headless:true,executablePath:process.env.PIT_BROWSER_EXECUTABLE});
  const receipt=[];
  try {
    for(const width of [390,1280]) {
      const context=await browser.newContext({viewport:{width,height:1000},isMobile:width<620,hasTouch:width<620,reducedMotion:"reduce"});
      await context.route("**/*",async route=>{
        const url=new URL(route.request().url());
        if(url.origin!==origin) return route.abort();
        if(url.pathname==="/api/moderation/source-credits" && route.request().method()==="GET") await new Promise(done=>setTimeout(done,200));
        return route.continue();
      });
      const page=await context.newPage();page.setDefaultTimeout(15000);
      const errors=[];page.on("pageerror",e=>errors.push(e.message));
      await page.goto(`${origin}/promotion-sources?edition=synthetic-http-edition`);
      await page.getByRole("heading",{name:"Sources",exact:true}).waitFor();
      await page.getByRole("heading",{name:"Synthetic standalone edition",exact:true}).waitFor();
      assert.ok(await page.getByText("Synthetic clip credit",{exact:false}).count());
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,"public page must fit viewport");
      await page.getByRole("link",{name:"Next credits",exact:true}).click();
      await page.getByText("Large creator 100",{exact:true}).waitFor();
      assert.equal(new URL(page.url()).searchParams.get("edition"),"synthetic-http-edition");
      await page.getByRole("link",{name:"Previous credits",exact:true}).click();
      await page.goto(`${origin}/promotion-sources?edition=synthetic-http-edition`);
      await page.keyboard.press("Tab");assert.equal(await page.evaluate(()=>document.activeElement.textContent),"Skip to content");
      await page.keyboard.press("Enter");
      await page.screenshot({path:resolve(directory,`edition-${width}.png`),fullPage:true});
      await page.getByLabel("Find a source or article").fill("no-such-synthetic-entry");await page.getByRole("button",{name:"Search",exact:true}).click();
      await page.getByText("No public articles match.",{exact:false}).waitFor();
      await page.screenshot({path:resolve(directory,`empty-${width}.png`),fullPage:true});
      await page.goto(`${origin}/promotion-sources?post=${postId}`);
      await page.getByText("Revised synthetic clip credit",{exact:false}).waitFor();
      await page.screenshot({path:resolve(directory,`article-${width}.png`),fullPage:true});
      await page.goto(`${origin}/promotion-sources?family=photos`);
      await page.getByRole("link",{name:"Source and licence details",exact:true}).first().waitFor();
      await page.screenshot({path:resolve(directory,`catalogue-photos-${width}.png`),fullPage:true});
      await page.goto(`${origin}/promotion-sources?family=providers`);await page.getByRole("heading",{name:"Deezer",exact:true}).waitFor();
      await page.screenshot({path:resolve(directory,`providers-${width}.png`),fullPage:true});
      const [name,value]=cookie.split("=");await context.addCookies([{name,value,url:origin}]);
      await page.goto(`${origin}/you`);
      await page.getByRole("button",{name:"Settings",exact:true}).waitFor();
      await page.getByRole("button",{name:"Settings",exact:true}).click();
      await page.getByText("Newsroom",{exact:true}).last().click();
      await page.getByLabel("Published article link for sources").waitFor();
      await page.getByLabel("Published article link for sources").fill(`${origin}/post/${postId}`.replace(origin,"https://www.mshpit.com"));
      await page.getByRole("button",{name:"Load credits",exact:true}).click();
      await page.getByText("Loading credits…",{exact:true}).waitFor();
      await page.getByText("Revised synthetic clip credit",{exact:false}).waitFor();
      await page.getByRole("button",{name:"Add source",exact:true}).click();
      const creator=page.getByLabel("Creator or source name",{exact:true}),urlField=page.getByLabel("Original HTTPS link",{exact:true});
      await creator.fill(`Synthetic music creator ${width} with a long descriptive credit name for this edition`);
      await creator.focus();await page.keyboard.press("Tab");assert.equal(await urlField.evaluate(el=>document.activeElement===el),true,"keyboard advances to original source link");
      await urlField.fill("https://www.nme.com/clip?token=synthetic-secret");
      await page.getByRole("button",{name:"music",exact:true}).click();
      await page.getByLabel("Credit text",{exact:true}).fill("A long readable music credit. ".repeat(20));
      const saveButton=page.getByRole("button",{name:"Save source",exact:true});
      await saveButton.focus();
      const invalidResponse=page.waitForResponse(r=>r.url().endsWith("/api/moderation/source-credits") && r.request().method()==="PUT");
      await page.keyboard.press("Enter");assert.equal((await invalidResponse).status(),400);
      await page.getByText(/Use a public HTTPS source link/).waitFor();
      await urlField.focus();await page.keyboard.press("ControlOrMeta+A");await page.keyboard.type(`https://www.nme.com/synthetic-music-${width}`);
      await saveButton.focus();const savedResponse=page.waitForResponse(r=>r.url().endsWith("/api/moderation/source-credits") && r.request().method()==="PUT");
      await page.keyboard.press("Enter");assert.equal((await savedResponse).status(),200);
      await page.getByText("Credit saved. Article content is unchanged.",{exact:true}).waitFor();
      await page.getByLabel("Credit text",{exact:true}).fill("Edited music attribution. ".repeat(10)+"\nSecond attribution line");
      const editedResponse=page.waitForResponse(r=>r.url().endsWith("/api/moderation/source-credits") && r.request().method()==="PUT");
      await saveButton.focus();await page.keyboard.press("Enter");assert.equal((await editedResponse).status(),200);
      await page.getByRole("button",{name:"Load credits",exact:true}).click();
      await page.getByText("Loading credits…",{exact:true}).waitFor({state:"hidden"});
      await page.getByText("Second attribution line",{exact:false}).first().waitFor();
      await page.getByRole("button",{name:"Save source",exact:true}).scrollIntoViewIfNeeded();
      await page.screenshot({path:resolve(directory,`admin-source-${width}.png`),fullPage:true});
      await page.getByRole("button",{name:"Edition",exact:true}).click();
      await page.getByLabel("Edition link name (lowercase words with hyphens)",{exact:true}).fill("synthetic-http-edition");
      await page.getByRole("button",{name:"Load credits",exact:true}).click();
      await page.getByText("Loading credits…",{exact:true}).waitFor({state:"hidden"});
      assert.equal(await page.getByLabel("Edition title",{exact:true}).inputValue(),"Synthetic standalone edition");
      await page.getByRole("button",{name:"Next credits",exact:true}).click();
      await page.getByText("Large creator 100",{exact:false}).waitFor();
      await page.getByRole("button",{name:"Previous credits",exact:true}).click();
      await page.getByText("Loading credits…",{exact:true}).waitFor({state:"hidden"});
      await page.getByRole("button",{name:"Save edition",exact:true}).scrollIntoViewIfNeeded();
      await page.screenshot({path:resolve(directory,`admin-edition-${width}.png`),fullPage:true});
      await page.goto(`${origin}/promotion-sources?post=${postId}`);
      await page.getByText("Edited music attribution.",{exact:false}).first().waitFor();
      await page.screenshot({path:resolve(directory,`long-credits-${width}.png`),fullPage:true});
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
      assert.deepEqual(errors,[]);receipt.push({width,passed:true,checks:["direct edition/article links","empty state","photo/provider collections","keyboard skip link","admin loading","keyboard field order","invalid URL recovery","keyboard add and edit persistence","long credits fit viewport","edition editor","no page errors"]});await context.close();
    }
    writeFileSync(resolve(directory,"browser-receipt.json"),JSON.stringify(receipt,null,2));
  } finally {await browser.close();}
}
