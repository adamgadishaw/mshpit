async function localServer() {
  const directory = resolve(root, process.env.PIT_PLAYER_BROWSER_DIST || "dist");
  const html = join(directory, "index.html");
  assert.ok(statSync(html).isFile(), "Export the current web build first.");
  const mime = { ".html":"text/html", ".js":"text/javascript", ".css":"text/css", ".png":"image/png", ".jpg":"image/jpeg", ".svg":"image/svg+xml", ".ttf":"font/ttf" };
  const server = createServer((request,response) => {
    if (request.method !== "GET" || request.url.startsWith("/api/")) return void response.writeHead(405).end();
    let file;
    try { file = resolve(directory, `.${decodeURIComponent(new URL(request.url, "http://fixture.invalid").pathname)}`); }
    catch { return void response.writeHead(400).end(); }
    if (!file.startsWith(directory + sep)) return void response.writeHead(400).end();
    try { if (!statSync(file).isFile()) file = html; } catch { file = html; }
    response.writeHead(200, { "Content-Type":mime[extname(file)] || "application/octet-stream", "Cache-Control":"no-store" });
    response.end(readFileSync(file));
  });
  await new Promise((done,reject) => { server.once("error",reject); server.listen(0,"127.0.0.1",done); });
  return {server,origin:`http://127.0.0.1:${server.address().port}`};
}

async function syntheticVideo(browser, width, height) {
  const page = await browser.newPage();
  try {
    // A visible changing canvas gives Chromium a real, decodable VP8 stream.
    // The generated bytes remain in memory and contain no downloaded footage.
    const base64 = await page.evaluate(async ({width,height}) => {
      const canvas = document.createElement("canvas"); canvas.width=width; canvas.height=height;
      const paint = canvas.getContext("2d");
      const stream = canvas.captureStream(12);
      const recorder = new MediaRecorder(stream,{mimeType:"video/webm;codecs=vp8"});
      const chunks=[];
      recorder.ondataavailable = event => { if(event.data.size) chunks.push(event.data); };
      const stopped = new Promise(done => { recorder.onstop=done; });
      let frame=0;
      const draw=()=> { paint.fillStyle=frame++%2 ? "#ff963b" : "#132c51"; paint.fillRect(0,0,width,height); paint.fillStyle="#ffffff"; paint.font="18px sans-serif"; paint.fillText("TEST VIDEO",16,height/2); };
      draw(); const timer=setInterval(draw,80); recorder.start(100);
      await new Promise(done=>setTimeout(done,10_000));
      recorder.stop(); await stopped; clearInterval(timer); stream.getTracks().forEach(track=>track.stop());
      const bytes=new Uint8Array(await new Blob(chunks,{type:"video/webm"}).arrayBuffer());
      let binary=""; for(const byte of bytes) binary+=String.fromCharCode(byte);
      return btoa(binary);
    },{width,height});
    const result=Buffer.from(base64,"base64");
    assert.ok(result.length>1000,"Synthetic fixture must contain real encoded frames.");
    return {bytes:result,width,height};
  } finally { await page.close(); }
}

