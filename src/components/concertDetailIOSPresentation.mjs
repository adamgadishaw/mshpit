// React Native reports live Dynamic Type changes through useWindowDimensions.
// Keep text-heavy columns stacked rather than resetting any screen/draft state.
export function concertDetailWide(width, fontScale, platform, threshold) {
  return width >= threshold && (platform !== "ios" || fontScale < 1.4);
}
